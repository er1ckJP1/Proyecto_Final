CREATE TABLE ROLES (
    id_rol                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol             VARCHAR2(50) NOT NULL UNIQUE,
    nivel_jerarquia        NUMBER(1) NOT NULL,
    puede_eliminar_ordenes CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT chk_rol_nivel CHECK (nivel_jerarquia IN (1, 2)),
    CONSTRAINT chk_rol_eliminar CHECK (puede_eliminar_ordenes IN ('S', 'N'))
);

CREATE TABLE LINEAS_PRODUCCION (
    id_linea      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_linea  VARCHAR2(20) NOT NULL UNIQUE,
    nombre_linea  VARCHAR2(100) NOT NULL,
    area          VARCHAR2(50) NOT NULL
);

CREATE TABLE CATALOGO_MOTIVOS_PARO (
    id_motivo    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_paro  VARCHAR2(20) NOT NULL UNIQUE,
    categoria    VARCHAR2(50) NOT NULL,
    descripcion  VARCHAR2(200) NOT NULL
);

CREATE TABLE EMPLEADOS (
    num_empleado     NUMBER(10) PRIMARY KEY,
    nombre_completo  VARCHAR2(120) NOT NULL,
    turno            VARCHAR2(20) NOT NULL,
    activo           CHAR(1) DEFAULT 'S' NOT NULL,
    id_rol           NUMBER NOT NULL,
    CONSTRAINT chk_emp_turno CHECK (turno IN ('MATUTINO', 'VESPERTINO', 'NOCTURNO')),
    CONSTRAINT chk_emp_activo CHECK (activo IN ('S', 'N')),
    CONSTRAINT fk_emp_rol FOREIGN KEY (id_rol) REFERENCES ROLES(id_rol)
);

CREATE TABLE ORDENES_PRODUCCION (
    id_produccion        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_lote          VARCHAR2(50) NOT NULL UNIQUE,
    numero_parte         VARCHAR2(50) NOT NULL,
    total_piezas_finales NUMBER(10) DEFAULT 0 NOT NULL,
    total_piezas_scrap   NUMBER(10) DEFAULT 0 NOT NULL,
    motivo_scrap         VARCHAR2(250) NULL,
    fecha_inicio         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    id_linea             NUMBER NOT NULL,
    num_empleado         NUMBER(10) NOT NULL,
    CONSTRAINT fk_ord_linea FOREIGN KEY (id_linea) REFERENCES LINEAS_PRODUCCION(id_linea),
    CONSTRAINT fk_ord_emp   FOREIGN KEY (num_empleado) REFERENCES EMPLEADOS(num_empleado)
);

CREATE TABLE TIEMPOS_MUERTOS (
    id_tiempo_muerto     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hora_inicio          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    hora_fin             TIMESTAMP NULL,
    id_produccion        NUMBER NOT NULL,
    id_motivo            NUMBER NULL,
    num_empleado_inicio  NUMBER(10) NOT NULL,
    num_empleado_fin     NUMBER(10) NULL,
    CONSTRAINT fk_tm_produccion FOREIGN KEY (id_produccion) REFERENCES ORDENES_PRODUCCION(id_produccion),
    CONSTRAINT fk_tm_motivo     FOREIGN KEY (id_motivo) REFERENCES CATALOGO_MOTIVOS_PARO(id_motivo),
    CONSTRAINT fk_tm_emp_ini    FOREIGN KEY (num_empleado_inicio) REFERENCES EMPLEADOS(num_empleado),
    CONSTRAINT fk_tm_emp_fin    FOREIGN KEY (num_empleado_fin) REFERENCES EMPLEADOS(num_empleado)
);